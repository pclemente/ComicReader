README_TEXT = """# Screenshot sample library

These nine CBZ books are demo fixtures for ComicReader App Store screenshots. They are generated by `../prepare_sample_library.py` and must not be added to the app target or shipped in the app bundle.

Each archive contains one designed cover followed by normalized reading copies of the three approved 1905 *Little Nemo in Slumberland* scans: `page-01.jpg`, `page-02.jpg`, and `page-04.jpg`. The 1907 `page-03.jpg` is deliberately excluded. The scans are by Winsor McCay and are public domain; full source URLs and credits are in `../sample-comics/sources.json`.
"""


def _font(candidates: tuple[tuple[str, int], ...], size: int) -> ImageFont.FreeTypeFont:
    for name, index in candidates:
        path = Path(name)
        if path.exists():
            return ImageFont.truetype(str(path), size=size, index=index)
        try:
            return ImageFont.truetype(name, size=size, index=index)
        except OSError:
            continue
    raise RuntimeError("No suitable TrueType font found")


DISPLAY_FONTS = (
    ("/System/Library/Fonts/Avenir Next Condensed.ttc", 0),
    ("/System/Library/Fonts/Supplemental/Futura.ttc", 4),
    ("DejaVuSansCondensed-Bold.ttf", 0),
)
SERIF_FONTS = (
    ("/System/Library/Fonts/Supplemental/Rockwell.ttc", 2),
    ("/System/Library/Fonts/Supplemental/Georgia Bold.ttf", 0),
    ("DejaVuSerif-Bold.ttf", 0),
)
BODY_FONTS = (
    ("/System/Library/Fonts/Avenir Next Condensed.ttc", 2),
    ("/System/Library/Fonts/HelveticaNeue.ttc", 1),
    ("DejaVuSans.ttf", 0),
)


def load_font(kind: str, size: int) -> ImageFont.FreeTypeFont:
    candidates = {"display": DISPLAY_FONTS, "serif": SERIF_FONTS, "body": BODY_FONTS}[kind]
    return _font(candidates, size)


def fit_font(text: str, kind: str, max_size: int, min_size: int, max_width: int) -> ImageFont.FreeTypeFont:
    for size in range(max_size, min_size - 1, -2):
        font = load_font(kind, size)
        left, _, right, _ = font.getbbox(text)
        if right - left <= max_width:
            return font
    return load_font(kind, min_size)


def draw_centered(draw: ImageDraw.ImageDraw, xy: tuple[int, int], text: str,
                  font: ImageFont.FreeTypeFont, fill: str, stroke_fill: str | None = None,
                  stroke_width: int = 0) -> None:
    draw.text(xy, text, font=font, fill=fill, anchor="ma",
              stroke_fill=stroke_fill, stroke_width=stroke_width)


def focal_crop(image: Image.Image, focal_x: float, focal_y: float,
               crop_width_fraction: float, target_size: tuple[int, int]) -> Image.Image:
    image = ImageOps.exif_transpose(image).convert("RGB")
    target_ratio = target_size[0] / target_size[1]
    crop_width = max(1, round(image.width * crop_width_fraction))
    crop_height = max(1, round(crop_width / target_ratio))
    if crop_height > image.height:
        crop_height = image.height
        crop_width = round(crop_height * target_ratio)

    center_x = round(image.width * focal_x)
    center_y = round(image.height * focal_y)
    left = max(0, min(image.width - crop_width, center_x - crop_width // 2))
    top = max(0, min(image.height - crop_height, center_y - crop_height // 2))
    crop = image.crop((left, top, left + crop_width, top + crop_height))
    crop = ImageEnhance.Contrast(crop).enhance(1.08)
    crop = ImageEnhance.Color(crop).enhance(0.92)
    crop = crop.resize(target_size, Image.Resampling.LANCZOS)
    if crop_width < target_size[0]:
        crop = crop.filter(ImageFilter.UnsharpMask(radius=1.2, percent=55, threshold=3))
    return crop


def add_paper_texture(image: Image.Image, seed: int, ink: str) -> None:
    rng = random.Random(seed)
    overlay = Image.new("RGBA", image.size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(overlay)
    ink_rgb = ImageColor.getrgb(ink)
    for _ in range(3600):
        x = rng.randrange(image.width)
        y = rng.randrange(image.height)
        alpha = rng.randrange(3, 13)
        draw.point((x, y), fill=(*ink_rgb, alpha))
    image.alpha_composite(overlay)


