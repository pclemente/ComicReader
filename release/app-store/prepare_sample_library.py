from PIL import ImageColor  # noqa: E402


def make_cover(volume: Volume, source_images: dict[str, Image.Image]) -> Image.Image:
    width, height = COVER_SIZE
    cover = Image.new("RGBA", COVER_SIZE, volume.background)
    draw = ImageDraw.Draw(cover)
    add_paper_texture(cover, volume.number, volume.foreground)

    # Archival double rule.
    draw.rounded_rectangle((28, 28, width - 28, height - 28), radius=10,
                           outline=volume.accent, width=18)
    draw.rounded_rectangle((51, 51, width - 51, height - 51), radius=7,
                           outline=volume.foreground, width=3)

    kicker_font = load_font("body", 31)
    draw_centered(draw, (width // 2, 83), "THE DREAMS OF", kicker_font, volume.foreground)

    display_font = fit_font("LITTLE NEMO", "display", 142, 96, width - 170)
    draw_centered(draw, (width // 2 + 4, 132 + 5), "LITTLE NEMO", display_font, volume.accent)
    draw_centered(draw, (width // 2, 132), "LITTLE NEMO", display_font, volume.foreground)

    rule_y = 290
    draw.line((82, rule_y, width - 82, rule_y), fill=volume.accent, width=9)
    draw.ellipse((width // 2 - 9, rule_y - 9, width // 2 + 9, rule_y + 9), fill=volume.foreground)

    art_box = (78, 330, width - 78, 1378)
    art_size = (art_box[2] - art_box[0], art_box[3] - art_box[1])
    art = focal_crop(source_images[volume.source], volume.focal_x, volume.focal_y,
                     volume.crop_width, art_size)

    # A restrained color wash ties all nine source crops to the cover system.
    wash = Image.new("RGB", art.size, volume.accent)
    art = Image.blend(art, wash, 0.055)
    shadow = (art_box[0] + 14, art_box[1] + 14, art_box[2] + 14, art_box[3] + 14)
    draw.rectangle(shadow, fill=volume.foreground)
    cover.alpha_composite(art.convert("RGBA"), dest=(art_box[0], art_box[1]))
    draw.rectangle(art_box, outline=volume.foreground, width=8)
    draw.rectangle((art_box[0] + 11, art_box[1] + 11, art_box[2] - 11, art_box[3] - 11),
                   outline=volume.accent, width=3)

    badge_x, badge_y = 95, 1308
    draw.ellipse((badge_x, badge_y, badge_x + 148, badge_y + 148),
                 fill=volume.accent, outline=volume.foreground, width=6)
    badge_small = load_font("body", 25)
    badge_large = load_font("display", 60)
    draw_centered(draw, (badge_x + 74, badge_y + 30), "VOL.", badge_small, volume.foreground)
    draw_centered(draw, (badge_x + 74, badge_y + 58), f"{volume.number:02d}", badge_large, volume.foreground)

    title_width = width - 180
    title_font = fit_font(volume.title, "serif", 69, 46, title_width)
    title_bbox = draw.textbbox((0, 0), volume.title, font=title_font)
    title_h = title_bbox[3] - title_bbox[1]
    title_y = 1480 if title_h <= 72 else 1460
    draw_centered(draw, (width // 2, title_y), volume.title, title_font, volume.foreground,
                  stroke_fill=volume.background, stroke_width=1)

    tagline_font = fit_font(volume.tagline, "body", 39, 28, width - 220)
    draw_centered(draw, (width // 2, title_y + title_h + 26), volume.tagline.upper(),
                  tagline_font, volume.accent)

    footer_font = load_font("body", 25)
    draw.line((230, 1710, width - 230, 1710), fill=volume.foreground, width=2)
    draw_centered(draw, (width // 2, 1733), "WINSOR McCAY  •  1905", footer_font, volume.foreground)
    return cover.convert("RGB")


def jpeg_bytes(image: Image.Image, quality: int) -> bytes:
    output = io.BytesIO()
    image.save(output, format="JPEG", quality=quality, optimize=True,
               progressive=True, subsampling=1)
    return output.getvalue()


def normalized_page_bytes(path: Path) -> bytes:
    with Image.open(path) as source:
        image = ImageOps.exif_transpose(source).convert("RGB")
        scale = PAGE_LONG_EDGE / max(image.size)
        target = (max(1, round(image.width * scale)), max(1, round(image.height * scale)))
        image = image.resize(target, Image.Resampling.LANCZOS)
        if scale > 1.0:
            image = image.filter(ImageFilter.UnsharpMask(radius=1.0, percent=45, threshold=3))
        return jpeg_bytes(image, quality=90)


def write_zip_member(archive: zipfile.ZipFile, name: str, payload: bytes) -> None:
    info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
    info.compress_type = zipfile.ZIP_STORED
    info.external_attr = 0o100644 << 16
    archive.writestr(info, payload)


def make_contact_sheet(covers: list[tuple[Volume, Image.Image]], destination: Path) -> None:
    thumb_size = (240, 360)
    margin = 28
    header = 84
    label_height = 42
    cell_width = thumb_size[0] + margin * 2
    cell_height = thumb_size[1] + label_height + margin
    sheet = Image.new("RGB", (cell_width * 3, header + cell_height * 3 + margin), CREAM)
    draw = ImageDraw.Draw(sheet)
    draw.text((sheet.width // 2, 28), "LITTLE NEMO · SAMPLE LIBRARY",
              font=load_font("display", 34), fill=NAVY, anchor="ma")
    label_font = load_font("body", 19)
    for index, (volume, cover) in enumerate(covers):
        column = index % 3
        row = index // 3
        x = column * cell_width + margin
        y = header + row * cell_height
        thumb = cover.resize(thumb_size, Image.Resampling.LANCZOS)
        sheet.paste(thumb, (x, y))
        draw.text((x + thumb_size[0] // 2, y + thumb_size[1] + 12),
                  f"{volume.number:02d} · {volume.title}", font=label_font,
                  fill=NAVY, anchor="ma")
    sheet.save(destination, format="JPEG", quality=88, optimize=True, progressive=True)


def prepare(output_dir: Path) -> None:
    missing = [name for name in APPROVED_PAGES if not (SOURCE_DIR / name).is_file()]
    if missing:
        raise FileNotFoundError(f"Missing approved source scans: {', '.join(missing)}")

    output_dir.mkdir(parents=True, exist_ok=True)
    covers_dir = output_dir / "covers"
    if covers_dir.exists():
        shutil.rmtree(covers_dir)
    covers_dir.mkdir()

    for old_archive in output_dir.glob("little-nemo-*.cbz"):
        old_archive.unlink()

    source_images: dict[str, Image.Image] = {}
    for name in APPROVED_PAGES:
        with Image.open(SOURCE_DIR / name) as image:
            source_images[name] = ImageOps.exif_transpose(image).convert("RGB")
    pages = {name: normalized_page_bytes(SOURCE_DIR / name) for name in APPROVED_PAGES}

    covers: list[tuple[Volume, Image.Image]] = []
    for volume in VOLUMES:
        cover = make_cover(volume, source_images)
        covers.append((volume, cover))
        cover_name = f"{volume.number:02d}-{volume.slug}.jpg"
        cover_path = covers_dir / cover_name
        cover_path.write_bytes(jpeg_bytes(cover, quality=92))

        archive_path = output_dir / f"little-nemo-{volume.number:02d}-{volume.slug}.cbz"
        page_order = APPROVED_PAGES[volume.number % 3:] + APPROVED_PAGES[:volume.number % 3]
        with zipfile.ZipFile(archive_path, "w") as archive:
            write_zip_member(archive, "000-cover.jpg", cover_path.read_bytes())
            for page_number, source_name in enumerate(page_order, start=1):
                write_zip_member(archive, f"{page_number:03d}-{Path(source_name).stem}.jpg", pages[source_name])

    make_contact_sheet(covers, output_dir / "cover-contact-sheet.jpg")
    (output_dir / "README.md").write_text(README_TEXT, encoding="utf-8")

    total_bytes = sum(path.stat().st_size for path in output_dir.glob("*.cbz"))
    print(f"Created {len(VOLUMES)} CBZ fixtures in {output_dir}")
    print(f"Combined archive size: {total_bytes / (1024 * 1024):.1f} MB")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_DIR,
                        help=f"output directory (default: {DEFAULT_OUTPUT_DIR})")
    args = parser.parse_args()
    prepare(args.output.resolve())


if __name__ == "__main__":
    main()
