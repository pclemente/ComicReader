#!/usr/bin/env python3
"""Build deterministic Little Nemo screenshot fixtures from approved 1905 scans.

Requires Pillow. The script deliberately reads only page-01.jpg, page-02.jpg,
and page-04.jpg; page-03.jpg is outside the approved source set.
"""

from __future__ import annotations

import argparse
import io
import random
import shutil
import zipfile
from dataclasses import dataclass
from pathlib import Path

from PIL import Image, ImageDraw, ImageEnhance, ImageFilter, ImageFont, ImageOps


SCRIPT_DIR = Path(__file__).resolve().parent
SOURCE_DIR = SCRIPT_DIR / "sample-comics"
DEFAULT_OUTPUT_DIR = SCRIPT_DIR / "sample-library"

APPROVED_PAGES = ("page-01.jpg", "page-02.jpg", "page-04.jpg")
PAGE_LONG_EDGE = 1800
COVER_SIZE = (1200, 1800)

CREAM = "#F3E2B8"
PAPER = "#E8CC91"
RED = "#A3372B"
NAVY = "#172B3A"
OCHRE = "#C58A2A"


@dataclass(frozen=True)
class Volume:
    number: int
    slug: str
    title: str
    tagline: str
    source: str
    focal_x: float
    focal_y: float
    crop_width: float
    background: str
    foreground: str
    accent: str


